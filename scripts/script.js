// 3. RENDERIZAR PAGINACIÓN
function renderPaginacion(totalPaginas) {
    paginacionNav.innerHTML = "";

    if (totalPaginas <= 1) return;

    const btnAnterior = document.createElement('button');
    btnAnterior.className = 'btn-paginacion';
    btnAnterior.textContent = '← Anterior';
    btnAnterior.disabled = paginaActual === 1;
    btnAnterior.addEventListener('click', () => {
        if (paginaActual > 1) {
            paginaActual--;
            renderCuentos(filtroActual);
            window.scrollTo({ top: 0, behavior: 'smooth' });
        }
    });
    paginacionNav.appendChild(btnAnterior);

    const info = document.createElement('span');
    info.className = 'info-paginacion';
    info.textContent = `Página ${paginaActual} de ${totalPaginas}`;
    paginacionNav.appendChild(info);

    for (let i = 1; i <= totalPaginas; i++) {
        const btn = document.createElement('button');
        btn.className = `btn-paginacion ${i === paginaActual ? 'active' : ''}`;
        btn.textContent = i;
        btn.addEventListener('click', () => {
            paginaActual = i;
            renderCuentos(filtroActual);
            window.scrollTo({ top: 0, behavior: 'smooth' });
        });
        paginacionNav.appendChild(btn);
    }

    const btnSiguiente = document.createElement('button');
    btnSiguiente.className = 'btn-paginacion';
    btnSiguiente.textContent = 'Siguiente →';
    btnSiguiente.disabled = paginaActual === totalPaginas;
    btnSiguiente.addEventListener('click', () => {
        if (paginaActual < totalPaginas) {
            paginaActual++;
            renderCuentos(filtroActual);
            window.scrollTo({ top: 0, behavior: 'smooth' });
        }
    });
    paginacionNav.appendChild(btnSiguiente);
}

